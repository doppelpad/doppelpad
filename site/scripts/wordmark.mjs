// Renders the "Doppelpad" wordmark from Space Grotesk Bold as outlined paths, so showing it
// loads no font, and the header logo: the app icon next to the wordmark, for dark and light
// backgrounds. Run it after changing the spacing or the colours below and commit the results.
//
//   npm run wordmark
//
//   src/assets/wordmark.svg     the wordmark alone, in currentColor
//   src/assets/logo-dark.svg    app icon + wordmark on dark backgrounds
//   src/assets/logo-light.svg   app icon + wordmark on light backgrounds
//
// Space Grotesk (Florian Karsten) is under the SIL Open Font License 1.1. The license covers
// the font files, not artwork made with them such as these outlines, and no font file ends up
// in the site.

import { readFile, writeFile } from 'node:fs/promises';
import opentype from 'opentype.js';

const FONT = new URL('../node_modules/@fontsource/space-grotesk/files/space-grotesk-latin-700-normal.woff', import.meta.url);
const ICON = new URL('../../gui/src-tauri/icons/source/app-icon.svg', import.meta.url);
const ASSETS = new URL('../src/assets/', import.meta.url);

const TEXT = 'Doppelpad';
/** Letter spacing in font units (1000 per em): tight, as display type wants it. */
const TRACKING = -30;
/**
 * Corrections for single letter pairs in font units, judged by eye on the rendered wordmark.
 * "pp" needs none: its bowl-to-stem gap matches "op" and stays below the stem-to-stem "lp".
 */
const PAIRS = {};
/** Wordmark colour in the header logo, per background. */
const COLOURS = { dark: '#e6e9ef', light: '#0f1115' };

const data = await readFile(FONT);
const font = opentype.parse(data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength));
const CAP = font.tables.os2.sCapHeight;

// The outlines in font units, y down, with the cap height at y = 0 and the first letter's ink at x = 0.
const glyphs = font.stringToGlyphs(TEXT);
const left = glyphs[0].getBoundingBox().x1;
let x = -left;
let right = 0;
let bottom = 0;
const paths = glyphs.map((g, i) => {
  const box = g.getBoundingBox();
  // getPath already turns the font's y-up outlines into SVG's y-down ones.
  const d = g.getPath(x, CAP, font.unitsPerEm).toPathData({ decimalPlaces: 1, flipY: false });
  right = x + box.x2;
  bottom = Math.max(bottom, CAP - box.y1);
  const next = glyphs[i + 1];
  if (next) x += g.advanceWidth + font.getKerningValue(g, next) + TRACKING + (PAIRS[TEXT[i] + TEXT[i + 1]] ?? 0);
  return d;
});
const width = Math.ceil(right);
const height = Math.ceil(bottom);
const outline = paths.join('');

const NOTE = '<!-- "Doppelpad" in Space Grotesk Bold (SIL Open Font License 1.1), outlined. Generated by site/scripts/wordmark.mjs. -->';

await writeFile(
  new URL('wordmark.svg', ASSETS),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" fill="currentColor">
  ${NOTE}
  <path d="${outline}"/>
</svg>
`,
);

// The logo in the icon's units: its 896-unit tile (64…960 of 1024) sets the height, the
// wordmark's cap height is about half of it and centred on it, the descenders hang below.
const icon = (await readFile(ICON, 'utf8')).replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
const scale = 440 / CAP;
const gap = 300;
const top = 512 - (CAP * scale) / 2;
const logoWidth = Math.ceil(960 + gap + width * scale + 8);

for (const [theme, colour] of Object.entries(COLOURS)) {
  await writeFile(
    new URL(`logo-${theme}.svg`, ASSETS),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="56 56 ${logoWidth - 56} 912">
  <!-- The app icon (gui/src-tauri/icons/source/app-icon.svg, the design for 48 px and up) and the wordmark, on ${theme} backgrounds. Generated by site/scripts/wordmark.mjs. -->
  <svg width="1024" height="1024" viewBox="0 0 1024 1024">
    ${icon}
  </svg>
  <path transform="translate(${960 + gap} ${top.toFixed(1)}) scale(${scale.toFixed(4)})" fill="${colour}" d="${outline}"/>
</svg>
`,
  );
}

console.log(`wordmark ${width} × ${height} font units; logo ${logoWidth - 56} × 912`);
