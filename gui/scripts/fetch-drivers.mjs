// Downloads the driver setups that the Windows installer bundles and checks them against
// pinned SHA-256 hashes. They land in src-tauri/installer/drivers/ (ignored by git),
// together with drivers.nsh, which gives the installer hooks their file names and versions.
//
//   node scripts/fetch-drivers.mjs
//
// `tauri build` runs this as part of `beforeBundleCommand`. Files that are already there
// with the right hash are not downloaded again.

import { createHash } from "node:crypto";
import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT_DIR = fileURLToPath(new URL("../src-tauri/installer/drivers/", import.meta.url));

// Official setups, signed by Nefarius Software Solutions e.U. The hashes match the winget
// manifests ViGEm.ViGEmBus 1.22.0 and Nefarius.HidHide 1.5.230. ViGEmBus 1.22.0 is the
// final release: the project was archived in November 2023.
const DRIVERS = [
  {
    key: "VIGEMBUS",
    name: "ViGEmBus",
    version: "1.22.0",
    file: "ViGEmBus_1.22.0_x64_x86_arm64.exe",
    url: "https://github.com/nefarius/ViGEmBus/releases/download/v1.22.0/ViGEmBus_1.22.0_x64_x86_arm64.exe",
    sha256: "89220a7865076b342892f98865f3499fb7c4cfd673159e89d352c360fd014c6a",
  },
  {
    key: "HIDHIDE",
    name: "HidHide",
    version: "1.5.230",
    file: "HidHide_1.5.230_x64.exe",
    url: "https://github.com/nefarius/HidHide/releases/download/v1.5.230.0/HidHide_1.5.230_x64.exe",
    sha256: "f4bbbcb82e6258641b887c74bc81c4c5f66e4aa811808dfc304347687b7605f6",
  },
];

const sha256 = (data) => createHash("sha256").update(data).digest("hex");

async function readIfExists(path) {
  try {
    return await readFile(path);
  } catch (e) {
    if (e.code === "ENOENT") return null;
    throw e;
  }
}

async function fetchDriver(d) {
  const dest = join(OUT_DIR, d.file);
  const existing = await readIfExists(dest);
  if (existing && sha256(existing) === d.sha256) {
    console.log(`${d.name} ${d.version}: present`);
    return;
  }

  console.log(`${d.name} ${d.version}: downloading ${d.url}`);
  const res = await fetch(d.url);
  if (!res.ok) throw new Error(`${d.name}: download failed with HTTP ${res.status}`);
  const data = Buffer.from(await res.arrayBuffer());
  const actual = sha256(data);
  if (actual !== d.sha256) {
    throw new Error(`${d.name}: SHA-256 mismatch\n  expected ${d.sha256}\n  got      ${actual}`);
  }
  // Write under a temporary name first, so an interrupted run never leaves a partial setup.
  await writeFile(`${dest}.part`, data);
  await rename(`${dest}.part`, dest);
  console.log(`${d.name} ${d.version}: ok (${data.length} bytes, SHA-256 verified)`);
}

function nsisDefines() {
  const lines = ["; Generated by scripts/fetch-drivers.mjs. Do not edit."];
  for (const d of DRIVERS) {
    lines.push(`!define DP_${d.key}_VERSION "${d.version}"`);
    lines.push(`!define DP_${d.key}_SETUP "${d.file}"`);
  }
  return lines.join("\r\n") + "\r\n";
}

await mkdir(OUT_DIR, { recursive: true });
try {
  for (const d of DRIVERS) await fetchDriver(d);
} catch (e) {
  for (const d of DRIVERS) await rm(join(OUT_DIR, `${d.file}.part`), { force: true });
  console.error(`fetch-drivers: ${e.message}`);
  process.exit(1);
}
await writeFile(join(OUT_DIR, "drivers.nsh"), nsisDefines());
